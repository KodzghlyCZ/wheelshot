List<String> modelsForBrand(String brand) {
  final needle = brand.trim().toLowerCase();
  for (final key in kTireBrands) {
    if (key.toLowerCase() == needle) {
      return List<String>.from(kTireModelsByBrand[key] ?? const []);
    }
  }
  // Fuzzy: brand typed with slight spelling variance
  for (final entry in kTireModelsByBrand.entries) {
    if (entry.key.toLowerCase().startsWith(needle) ||
        needle.startsWith(entry.key.toLowerCase())) {
      return List<String>.from(entry.value);
    }
  }
  return const [];
}
